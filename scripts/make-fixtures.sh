#!/usr/bin/env bash
# Regenerates the test fixtures. Every fixture is generated here, never a real
# family Photo, because the repo is public (ADR-0001). Needs ImageMagick and
# heif-enc (libheif), and curl for the public-domain crew portrait.
set -euo pipefail
cd "$(dirname "$0")/.."
exiftool="$(ls node_modules/.pnpm/exiftool-vendored.pl@*/node_modules/exiftool-vendored.pl/bin/exiftool | head -1)"
out=fixtures

# A small gradient with full EXIF and GPS, as a camera would write it.
magick -size 64x48 gradient:steelblue-orange -strip "$out/full-exif.jpg"
"$exiftool" -q -overwrite_original \
  -Make="Canon" -Model="Canon EOS R6" -LensModel="RF24-105mm F4 L IS USM" \
  -ExposureTime=0.004 -FNumber=4 -ISO=200 -FocalLength=50 \
  -DateTimeOriginal="2024:07:04 18:30:00" -OffsetTimeOriginal="-07:00" \
  -GPSLatitude=37.7749 -GPSLatitudeRef=N -GPSLongitude=122.4194 -GPSLongitudeRef=W \
  "$out/full-exif.jpg"

# Same image recorded sideways: Orientation 6 means "rotate 90 CW to view".
magick -size 64x48 gradient:steelblue-orange -strip "$out/rotated.jpg"
"$exiftool" -q -overwrite_original -Orientation#=6 -Make="Apple" -Model="iPhone 15" "$out/rotated.jpg"

# A one-page PDF: a real file that is not a Photo, for the 415 rejection.
magick -size 16x16 xc:white "$out/not-a-photo.pdf"

# A phone shot with a Date taken but no GPS Fields and no timezone offset.
magick -size 64x48 gradient:seagreen-khaki -strip "$out/no-location.jpg"
"$exiftool" -q -overwrite_original \
  -Make="Google" -Model="Pixel 8" -DateTimeOriginal="2023:12:25 09:15:00" \
  "$out/no-location.jpg"

# One Field in every Section: GPS, IPTC, XMP, an ICC profile, and Canon Maker
# notes. The ICC profile is generated by Little CMS (linkicc, from lcms2), and
# the Maker notes are a hand-built Canon IFD holding one entry, ModelID
# 0x80000453 (EOS R6), so nothing here comes from a real camera or Photo.
magick -size 64x48 gradient:steelblue-orange -strip "$out/every-section.jpg"
icc="$(mktemp)"; makernotes="$(mktemp)"
trap 'rm -f "$icc" "$makernotes"' EXIT
rm -f "$icc"; linkicc -o "$icc" '*sRGB' '*sRGB' >/dev/null
printf '\x00\x01\x00\x10\x00\x04\x00\x00\x00\x01\x80\x00\x04\x53\x00\x00\x00\x00' > "$makernotes"
"$exiftool" -q -overwrite_original \
  -Make="Canon" -Model="Canon EOS R6" "-MakerNoteCanon<=$makernotes" "-ICC_Profile<=$icc" \
  -GPSLatitude=37.7749 -GPSLatitudeRef=N -GPSLongitude=122.4194 -GPSLongitudeRef=W \
  -IPTC:Caption-Abstract="Family at the beach" -XMP-dc:Title="Beach day" \
  "$out/every-section.jpg"

# Stripped of all metadata, as a messaging app would send it.
magick -size 64x48 gradient:steelblue-orange -strip "$out/no-metadata.jpg"

# Has EXIF (camera Fields) but no Date taken.
magick -size 64x48 gradient:steelblue-orange -strip "$out/no-date-taken.jpg"
"$exiftool" -q -overwrite_original -Make="Canon" -Model="Canon EOS R6" "$out/no-date-taken.jpg"

# The full-EXIF JPEG cut off partway through its image data, as an interrupted
# copy leaves it. Its EXIF still reads.
head -c 700 "$out/full-exif.jpg" > "$out/truncated.jpg"

# A healthy JPEG whose maker notes are an unrecognized blob from a made-up
# camera maker. ExifTool flags that with a "[minor]" warning, which says nothing
# about the file's structure.
makernotes_unknown="$(mktemp)"
printf 'ACME\x00\x00not an ifd at all' > "$makernotes_unknown"
magick -size 64x48 gradient:steelblue-orange -strip "$out/minor-warning.jpg"
"$exiftool" -q -overwrite_original \
  -Make="Acme" -Model="Acme One" "-MakerNoteUnknown<=$makernotes_unknown" \
  -DateTimeOriginal="2024:07:04 18:30:00" -OffsetTimeOriginal="-07:00" \
  "$out/minor-warning.jpg"
rm -f "$makernotes_unknown"

# The same JPEG cut off before its image data: the minor warning comes
# first, and must not hide the truncation.
head -c 500 "$out/minor-warning.jpg" > "$out/truncated-minor-warning.jpg"

# The full-EXIF JPEG with a UserComment whose 8-byte character code is not one
# EXIF defines. ExifTool warns "Invalid EXIF text encoding", a full warning that
# is about one Field's text, not the file's structure. ExifTool writes the code
# "ASCII\0\0\0"; the byte patch swaps it for "BOGUS\0\0\0".
cp "$out/full-exif.jpg" "$out/bad-text-encoding.jpg"
"$exiftool" -q -overwrite_original -UserComment="Family at the beach" "$out/bad-text-encoding.jpg"
LC_ALL=C perl -0777 -pi -e 's/ASCII\0\0\0Family/BOGUS\0\0\0Family/' "$out/bad-text-encoding.jpg"

# The same JPEG cut off before its image data: ExifTool reports the text
# encoding warning first, and it must not hide the truncation.
head -c 750 "$out/bad-text-encoding.jpg" > "$out/truncated-bad-text-encoding.jpg"

# iPhone-style HEIC: landscape pixels (red top half, blue bottom half) that an
# iPhone held upright would record, with both an HEIF irot box and EXIF
# Orientation 6. heif-enc turns the source JPEG's Orientation into the irot box
# and keeps the EXIF, as an iPhone does. Viewed upright it is portrait, red on
# the right.
tmp="$(mktemp -d)"
# Replaces the earlier trap, so it cleans up every temporary file.
trap 'rm -rf "$icc" "$makernotes" "$tmp"' EXIT
magick -size 64x24 xc:red -size 64x24 xc:blue -append -strip "$tmp/iphone.jpg"
"$exiftool" -q -overwrite_original -Orientation#=6 -Make="Apple" -Model="iPhone 15 Pro" \
  -DateTimeOriginal="2024:07:04 18:30:00" -OffsetTimeOriginal="-07:00" "$tmp/iphone.jpg"
heif-enc -q 90 -o "$out/iphone.heic" "$tmp/iphone.jpg"

# The same pixels as a HEIC with EXIF Orientation 6 but no irot box, as some
# non-Apple encoders write it: encoded from a JPEG with no Orientation, so
# heif-enc adds no irot, then given the EXIF Orientation afterwards. Viewed
# upright it is portrait, red on the right.
magick -size 64x24 xc:red -size 64x24 xc:blue -append -strip "$tmp/exif-oriented.jpg"
heif-enc -q 90 -o "$out/exif-oriented.heic" "$tmp/exif-oriented.jpg"
"$exiftool" -q -overwrite_original -Orientation#=6 -Make="Samsung" -Model="Galaxy S24" \
  -DateTimeOriginal="2024:07:04 18:30:00" -OffsetTimeOriginal="-07:00" "$out/exif-oriented.heic"

# Formats the browser previews itself, and formats with no preview in v1.
magick -size 64x48 gradient:steelblue-orange -strip "$out/gradient.png"
magick -size 64x48 gradient:steelblue-orange -strip "$out/gradient.webp"

# A PNG whose only metadata is in PNG text chunks, as many editors and
# screenshot tools write it.
magick -size 64x48 gradient:steelblue-orange -strip "$out/text-chunks.png"
"$exiftool" -q -overwrite_original -PNG:Title="Beach day" -PNG:Comment="Family at the beach" "$out/text-chunks.png"
magick -size 64x48 gradient:steelblue-orange -strip -compress zip "$out/scan.tif"
"$exiftool" -q -overwrite_original -Make="Epson" -Model="Perfection V600" "$out/scan.tif"

# A minimal RAW: a TIFF that ExifTool recognizes as DNG from its DNGVersion.
cp "$out/scan.tif" "$out/raw.dng"
"$exiftool" -q -overwrite_original -DNGVersion="1.4.0.0" -Make="Canon" -Model="Canon EOS R6" "$out/raw.dng"

# Photos with known Faces, for face detection. NASA's Apollo 11 crew portrait
# (S69-31739) is public domain as a work of the US government, so it is not a
# family Photo; it is downloaded at a pinned checksum and shrunk. Upright, the
# Faces are Armstrong (left), Collins (centre, highest) and Aldrin (right).
curl --fail --location --silent --show-error -A "family-photos-fixtures" -o "$tmp/apollo11.jpg" \
  "https://upload.wikimedia.org/wikipedia/commons/3/3d/Apollo_11_Crew.jpg"
echo "ba9ccc7c8accc044ebe71fbe402255d45f4cb0fec67f2c9afbfb4ed71d671784  $tmp/apollo11.jpg" | sha256sum --check --quiet
magick "$tmp/apollo11.jpg" -resize 800x800 -strip -quality 80 "$out/crew.jpg"

# The same Photo stored sideways with EXIF Orientation 6 ("rotate 90 CW to
# view"), as a phone held upright records it. Upright it matches crew.jpg.
magick "$out/crew.jpg" -rotate -90 -strip -quality 80 "$out/crew-rotated.jpg"
"$exiftool" -q -overwrite_original -Orientation#=6 "$out/crew-rotated.jpg"

# The sideways pixels as a HEIC with EXIF Orientation 6 and no irot box.
magick "$out/crew.jpg" -rotate -90 -strip "$tmp/crew-sideways.jpg"
heif-enc -q 80 -o "$out/crew-oriented.heic" "$tmp/crew-sideways.jpg"
"$exiftool" -q -overwrite_original -Orientation#=6 "$out/crew-oriented.heic"

# The crew as a TIFF: the viewer finds no Faces in TIFF, even when it shows some.
magick "$out/crew.jpg" -compress jpeg "$out/crew.tif"

# A corner of the same Photo, background and Moon only, with no Faces.
magick "$out/crew.jpg" -crop 300x180+0+0 +repage -quality 80 "$out/no-faces.jpg"
